let seq = 0;
/** Applique un plan comme le ferait le store (pour tester l'idempotence). */
function apply(tasks: Task[], plan: ReturnType<typeof planTasks>): Task[] {
  let out = tasks.map((x) => {
    const u = plan.update.find((p) => p.id === x.id);
    return u ? { ...x, ...u.patch } : x;
  });
  out = out.map((x) => (plan.cancel.includes(x.id) ? { ...x, status: "cancelled" as const } : x));
  for (const d of plan.create) {
    out.push({ ...d, id: `t${++seq}`, status: "unassigned", isAutoGenerated: true, createdAt: "x" });
  }
  return out;
}

const NOW = new Date("2026-11-01T08:00:00Z");

describe("génération des ménages", () => {
  it("crée une rotation entre deux séjours, à J = prioritaire", () => {
    const r1 = res("r1", "2026-11-02T15:00:00Z", "2026-11-05T10:00:00Z");
    const r2 = res("r2", "2026-11-05T15:00:00Z", "2026-11-08T10:00:00Z", { guestsCount: 3 });
    const drafts = expectedTasks(property(), [r2, r1], NOW);
    const t1 = drafts.find((d) => d.reservationId === "r1")!;
    expect(t1.type).toBe("turnover");
    expect(t1.windowStart).toBe("2026-11-05T10:00:00.000Z");
    expect(t1.windowEnd).toBe("2026-11-05T15:00:00.000Z");
    expect(t1.priority).toBe("high");
    expect(t1.nextReservationId).toBe("r2");
    expect(t1.guestsCount).toBe(3);
  });

  it("sans séjour suivant : fenêtre ouverte 3 jours, priorité normale", () => {
    const drafts = expectedTasks(property(), [res("r1", "2026-11-02T15:00:00Z", "2026-11-05T10:00:00Z")], NOW);
    expect(drafts[0].windowEnd).toBe("2026-11-08T10:00:00.000Z");
    expect(drafts[0].priority).toBe("normal");
  });

  it("fenêtre plus courte que le ménage : aucun ménage impossible, un conflit signalé", () => {
    const rs = [res("r1", "2026-11-02T15:00:00Z", "2026-11-05T10:00:00Z"), res("r2", "2026-11-05T11:00:00Z", "2026-11-06T10:00:00Z")];
    expect(expectedTasks(property(), rs, NOW).find((d) => d.reservationId === "r1")).toBeUndefined();
    expect(scheduleConflicts(property(), rs, NOW)).toEqual([
      { kind: "gap_too_short", propertyId: "p1", reservationId: "r1", nextReservationId: "r2", availableMin: 60, neededMin: 120 },
    ]);
  });
  it("ignore les blocages et ajoute accueil/départ si le service est activé", () => {
    const drafts = expectedTasks(
      property({ checkInService: true, checkOutService: true }),
      [res("r1", "2026-11-02T15:00:00Z", "2026-11-05T10:00:00Z"), res("b", "2026-11-10T15:00:00Z", "2026-11-12T10:00:00Z", { status: "blocked" })],
      NOW,
    );
    expect(drafts.map((d) => d.type).sort()).toEqual(["check_in", "check_out", "turnover"]);
  });

  it("est idempotent : relancer ne crée aucun doublon", () => {
    const p = property();
    const reservations = [res("r1", "2026-11-02T15:00:00Z", "2026-11-05T10:00:00Z"), res("r2", "2026-11-05T15:00:00Z", "2026-11-08T10:00:00Z")];
    let tasks = apply([], planTasks(p, reservations, [], NOW));
    expect(tasks).toHaveLength(2);
    const second = planTasks(p, reservations, tasks, NOW);
    expect(second.create).toHaveLength(0);
    expect(second.update).toHaveLength(0);
    expect(second.cancel).toHaveLength(0);
    tasks = apply(tasks, second);
    expect(tasks).toHaveLength(2);
  });

  it("annule la tâche assignée d'une réservation annulée et prévient l'agent", () => {
    const p = property();
    const r1 = res("r1", "2026-11-02T15:00:00Z", "2026-11-05T10:00:00Z");
    let tasks = apply([], planTasks(p, [r1], [], NOW));
    tasks = tasks.map((x) => ({ ...x, assigneeId: "a1", status: "assigned" as const }));
    const plan = planTasks(p, [{ ...r1, status: "cancelled" }], tasks, NOW);
    expect(plan.cancel).toEqual([tasks[0].id]);
    expect(plan.notify[0]).toMatchObject({ kind: "task_cancelled", assigneeId: "a1" });
  });

  it("ne touche jamais une tâche en cours", () => {
    const p = property();
    const r1 = res("r1", "2026-11-02T15:00:00Z", "2026-11-05T10:00:00Z");
    let tasks = apply([], planTasks(p, [r1], [], NOW));
    tasks = tasks.map((x) => ({ ...x, status: "in_progress" as const }));
    const plan = planTasks(p, [{ ...r1, status: "cancelled" }], tasks, NOW);
    expect(plan.cancel).toHaveLength(0);
  });

  it("met à jour la fenêtre quand une réservation suivante arrive", () => {
    const p = property();
    const r1 = res("r1", "2026-11-02T15:00:00Z", "2026-11-05T10:00:00Z");
    let tasks = apply([], planTasks(p, [r1], [], NOW));
    tasks = tasks.map((x) => ({ ...x, assigneeId: "a1", status: "assigned" as const }));
    const plan = planTasks(p, [r1, res("r2", "2026-11-05T14:00:00Z", "2026-11-07T10:00:00Z")], tasks, NOW);
    expect(plan.update[0].patch.windowEnd).toBe("2026-11-05T14:00:00.000Z");
    expect(plan.update[0].patch.priority).toBe("high");
    expect(plan.notify[0].kind).toBe("task_changed");
  });
});

describe("conflits et répartition", () => {
  const task = (id: string, start: string, end: string, over: Partial<Task> = {}): Task => ({
    id,
    propertyId: "p1",
    type: "turnover",
    status: "assigned",
    priority: "normal",
    isAutoGenerated: true,
    windowStart: start,
    windowEnd: end,
    durationMin: 120,
    createdAt: "x",
    ...over,
  });

  it("détecte un chevauchement et un dépassement de fenêtre", () => {
    const a = task("a", "2026-11-05T09:00:00Z", "2026-11-05T15:00:00Z", { assigneeId: "x", scheduledStart: "2026-11-05T10:00:00Z" });
    const b = task("b", "2026-11-05T09:00:00Z", "2026-11-05T12:30:00Z", { assigneeId: "x", scheduledStart: "2026-11-05T11:00:00Z" });
    const c = detectConflicts([a, b]);
    expect(c.filter((x) => x.kind === "overlap")).toHaveLength(2);
    expect(c.find((x) => x.kind === "outside_window")?.taskId).toBe("b");
  });

  it("conflictsIfAssigned prévient avant d'assigner", () => {
    const busy = task("a", "2026-11-05T09:00:00Z", "2026-11-05T15:00:00Z", { assigneeId: "x", scheduledStart: "2026-11-05T10:00:00Z" });
    const candidate = task("b", "2026-11-05T09:00:00Z", "2026-11-05T15:00:00Z", { status: "unassigned" });
    expect(conflictsIfAssigned(candidate, "x", "2026-11-05T11:00:00Z", [busy, candidate])).toHaveLength(1);
    expect(conflictsIfAssigned(candidate, "x", "2026-11-05T12:00:00Z", [busy, candidate])).toHaveLength(0);
  });

  it("répartit sans conflit, les plus pressées d'abord, en équilibrant", () => {
    const t1 = task("t1", "2026-11-05T10:00:00Z", "2026-11-05T14:00:00Z", { status: "unassigned" });
    const t2 = task("t2", "2026-11-05T10:00:00Z", "2026-11-05T12:00:00Z", { status: "unassigned" });
    const t3 = task("t3", "2026-11-05T10:00:00Z", "2026-11-05T18:00:00Z", { status: "unassigned" });
    const result = autoAssign([t1, t2, t3], ["x", "y"], []);
    expect(result).toHaveLength(3);
    const placed = [t1, t2, t3].map((t) => {
      const r = result.find((x) => x.taskId === t.id)!;
      return { ...t, assigneeId: r.agentId, scheduledStart: r.scheduledStart, status: "assigned" as const };
    });
    expect(detectConflicts(placed)).toHaveLength(0);
    expect(result.find((r) => r.taskId === "t2")!.scheduledStart).toBe("2026-11-05T10:00:00.000Z");
  });

  it("laisse non assignée une tâche impossible à placer", () => {
    const t1 = task("t1", "2026-11-05T10:00:00Z", "2026-11-05T11:00:00Z", { status: "unassigned" });
    expect(autoAssign([t1], ["x"], [])).toHaveLength(0);
  });
});

