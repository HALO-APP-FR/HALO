import { describe, expect, it } from "vitest";
import { missionVsArrival } from "@/lib/engine/prep-conflicts";
import type { Task } from "@/lib/domain/types";

const NOW = new Date("2026-11-19T08:00:00Z");
const base = { id: "m", status: "assigned" as Task["status"], windowStart: "2026-11-20T10:00:00Z", windowEnd: "2026-11-20T13:00:00Z", durationMin: 30, scheduledStart: undefined as string | undefined, assigneeId: "a" as string | undefined, isAutoGenerated: true };

/** Brief du 5/11 : mission nécessaire avant l'arrivée — impossible / à vérifier / inconnu / possible (jamais une garantie). */
describe("mission liée vs arrivée confirmée", () => {
  it("cas du 5/11 : arrivée 14 h, début au plus tôt 14 h, 30 min, échéance 16 h, plage manuelle → impossible, signalée manuelle", () => {
    const r = missionVsArrival({ ...base, windowStart: "2026-11-20T13:00:00Z", windowEnd: "2026-11-20T15:00:00Z", isAutoGenerated: false }, "2026-11-20T13:00:00Z", NOW);
    expect(r).toMatchObject({ level: "impossible", reasons: ["cannot_finish"], manual: true });
  });
  it("tient avant l'arrivée, rien d'autre → possible (d'après les données connues)", () => {
    expect(missionVsArrival(base, "2026-11-20T15:00:00Z", NOW)).toMatchObject({ level: "possible", reasons: [] });
  });
  it("plage qui finit après l'arrivée, créneau trop tardif, personne attribué → à vérifier, chaque raison listée", () => {
    const r = missionVsArrival({ ...base, windowEnd: "2026-11-20T16:00:00Z", scheduledStart: "2026-11-20T14:45:00Z", assigneeId: undefined }, "2026-11-20T15:00:00Z", NOW);
    expect(r).toMatchObject({ level: "at_risk", reasons: ["slot_after_arrival", "deadline_after_arrival", "unassigned"] });
  });
  it("mission en cours : avancement inconnu (jamais déclarée impossible) ; heure passée : à vérifier", () => {
    expect(missionVsArrival({ ...base, status: "in_progress" as Task["status"] }, "2026-11-20T15:00:00Z", NOW).level).toBe("unknown");
    expect(missionVsArrival({ ...base, status: "in_progress" as Task["status"] }, "2026-11-19T07:00:00Z", NOW)).toMatchObject({ level: "at_risk", reasons: ["in_progress", "arrival_passed"] });
  });
  it("arrivée avancée (décision d'horaire) : une mission qui tenait devient impossible", () => {
    expect(missionVsArrival(base, "2026-11-20T14:00:00Z", NOW).level).toBe("possible");
    expect(missionVsArrival(base, "2026-11-20T10:15:00Z", NOW).level).toBe("impossible");
  });
});
