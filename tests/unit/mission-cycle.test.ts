import { beforeEach, describe, expect, it } from "vitest";
import type { Member, Property, Task } from "@/lib/domain/types";
import { canRequestCorrection, canStart, canSubmit, canValidate, missingRequiredPhotos, needsValidation } from "@/lib/engine/mission-cycle";
import { useHalo } from "@/lib/store/halo-store";

const property = {
  id: "p1",
  timezone: "Europe/Paris",
  checklist: [{ id: "r1", name: "Bain", items: [{ id: "i1", label: "Douche", photoRequired: true }, { id: "i2", label: "Miroir", photoRequired: false }] }],
} as unknown as Property;

const task = (over: Partial<Task> = {}): Task => ({
  id: "t1",
  propertyId: "p1",
  type: "turnover",
  status: "in_progress",
  priority: "normal",
  isAutoGenerated: true,
  windowStart: "2026-10-28T09:00:00Z",
  windowEnd: "2026-10-28T13:00:00Z",
  durationMin: 90,
  assigneeId: "a1",
  createdAt: "2026-10-27T09:00:00Z",
  ...over,
});
const manager = { id: "m1", role: "manager", active: true } as Member;
const agent = { id: "a1", role: "agent", active: true } as Member;

describe("cycle de mission : règles", () => {
  it("seul l'agent assigné démarre et soumet", () => {
    expect(canStart(task({ status: "assigned" }), "a2")).toEqual({ ok: false, reason: "not_assignee" });
    expect(canStart(task({ status: "assigned" }), "a1").ok).toBe(true);
    expect(canStart(task({ status: "done" }), "a1")).toEqual({ ok: false, reason: "bad_status" });
    expect(canSubmit(task(), property, "a2")).toEqual({ ok: false, reason: "not_assignee" });
    expect(canSubmit(task({ status: "assigned" }), property, "a1")).toEqual({ ok: false, reason: "bad_status" });
  });
  it("photos obligatoires exigées avant la soumission (ménage et contrôle seulement)", () => {
    expect(canSubmit(task(), property, "a1")).toEqual({ ok: false, reason: "missing_photos", missing: 1 });
    expect(canSubmit(task({ report: { checked: [], photos: { i1: ["ph1"] }, rooms: {} } }), property, "a1").ok).toBe(true);
    // Un accueil ne suit pas la checklist de ménage
    expect(missingRequiredPhotos(task({ type: "check_in" }), property)).toEqual([]);
  });
  it("validation configurable par type de mission", () => {
    expect(needsValidation("turnover", undefined)).toBe(true);
    expect(needsValidation("check_in", undefined)).toBe(false);
    expect(needsValidation("turnover", [])).toBe(false);
  });
  it("seul un responsable valide ou demande une correction, avec un motif", () => {
    expect(canValidate(task({ status: "done" }), agent)).toEqual({ ok: false, reason: "not_manager" });
    expect(canValidate(task({ status: "in_progress" }), manager)).toEqual({ ok: false, reason: "bad_status" });
    expect(canValidate(task({ status: "done" }), manager).ok).toBe(true);
    expect(canValidate(task({ status: "done" }), { ...manager, active: false })).toEqual({ ok: false, reason: "not_manager" });
    expect(canRequestCorrection(task({ status: "done" }), manager, "  ")).toEqual({ ok: false, reason: "reason_required" });
    expect(canRequestCorrection(task({ status: "done" }), agent, "x")).toEqual({ ok: false, reason: "not_manager" });
  });
});

describe("cycle de mission : magasin de la démo", () => {
  beforeEach(() => useHalo.getState().resetDemo("fr"));

  const setup = () => {
    const s = useHalo.getState();
    const p = s.properties.find((x) => x.checklist.some((r) => r.items.some((i) => i.photoRequired)))!;
    const agentId = s.members.find((m) => m.role === "agent" && m.position === "housekeeper")!.id;
    const id = s.addTask({ propertyId: p.id, type: "turnover", windowStart: new Date().toISOString(), windowEnd: new Date(Date.now() + 4 * 3_600_000).toISOString(), durationMin: 60, assigneeId: agentId });
    return { p, agentId, id, managerId: s.members.find((m) => m.role === "owner")!.id };
  };
  const get = (id: string) => useHalo.getState().tasks.find((x) => x.id === id)!;

  it("démarrer → soumettre (photos) → correction → reprise → validation, tout est tracé", () => {
    const { p, agentId, id, managerId } = setup();
    const st = useHalo.getState();
    expect(st.startTask(id, "quelqu-un-d-autre").ok).toBe(false);
    expect(st.startTask(id, agentId).ok).toBe(true);
    expect(st.submitTask(id, agentId)).toMatchObject({ ok: false, reason: "missing_photos" });
    expect(get(id).status).toBe("in_progress");
    const photos = Object.fromEntries(p.checklist.flatMap((r) => r.items).filter((i) => i.photoRequired).map((i) => [i.id, ["ph"]]));
    st.updateTaskReport(id, (r) => ({ ...r, photos }));
    expect(st.submitTask(id, agentId)).toMatchObject({ ok: true, status: "done" });
    expect(st.validateTask(id, agentId).ok).toBe(false);
    expect(st.requestCorrection(id, managerId, "").ok).toBe(false);
    expect(st.requestCorrection(id, managerId, "Douche à reprendre").ok).toBe(true);
    expect(get(id)).toMatchObject({ status: "to_redo", correctionReason: "Douche à reprendre" });
    expect(get(id).reportHistory).toHaveLength(1);
    expect(get(id).notes).toBeUndefined();
    expect(st.startTask(id, agentId).ok).toBe(true);
    expect(st.submitTask(id, agentId).ok).toBe(true);
    expect(st.validateTask(id, managerId).ok).toBe(true);
    expect(get(id).status).toBe("validated");
    expect(get(id).events?.map((e) => e.kind)).toEqual(["started", "submitted", "correction_requested", "started", "submitted", "validated"]);
    expect(get(id).events?.[2]).toMatchObject({ note: "Douche à reprendre" });
  });

  it("type sans validation : validée automatiquement à la soumission", () => {
    const { p, agentId } = setup();
    const st = useHalo.getState();
    const id = st.addTask({ propertyId: p.id, type: "check_in", windowStart: new Date().toISOString(), windowEnd: new Date(Date.now() + 3_600_000).toISOString(), durationMin: 30, assigneeId: agentId });
    st.startTask(id, agentId);
    expect(st.submitTask(id, agentId)).toMatchObject({ ok: true, status: "validated" });
    expect(get(id).events?.at(-1)?.kind).toBe("auto_validated");
  });
});
