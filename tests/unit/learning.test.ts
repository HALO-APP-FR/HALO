import { describe, expect, it } from "vitest";
import type { Property, Task } from "@/lib/domain/types";
import { actualMinutes, averageGap, learnedCleaningDuration, withLearnedDuration, workedMinutes } from "@/lib/engine/learning";
import { placeTask } from "@/lib/engine/schedule";
import { decodeGuide, encodeGuide, guidePayload } from "@/lib/engine/guide-link";

let n = 0;
const done = (startIso: string, minutes: number, over: Partial<Task> = {}): Task => ({
  id: `t${++n}`,
  propertyId: "p1",
  type: "turnover",
  status: "validated",
  priority: "normal",
  isAutoGenerated: true,
  windowStart: startIso,
  windowEnd: startIso,
  durationMin: 120,
  assigneeId: "a1",
  startedAt: startIso,
  completedAt: new Date(new Date(startIso).getTime() + minutes * 60_000).toISOString(),
  createdAt: startIso,
  ...over,
});

const property = { id: "p1", cleaningDurationMin: 120 } as Property;

describe("durées apprises", () => {
  it("durée réelle d'une mission pointée", () => {
    expect(actualMinutes(done("2026-10-01T09:00:00Z", 95))).toBe(95);
    expect(actualMinutes({ startedAt: "2026-10-01T09:00:00Z" })).toBeNull();
    // Pointage oublié toute la nuit : ignoré
    expect(actualMinutes(done("2026-10-01T09:00:00Z", 900))).toBeNull();
  });
  it("pas assez d'historique : on garde la durée saisie", () => {
    const tasks = [done("2026-10-01T09:00:00Z", 90), done("2026-10-02T09:00:00Z", 95)];
    expect(learnedCleaningDuration("p1", tasks)).toBeNull();
    expect(withLearnedDuration(property, tasks).cleaningDurationMin).toBe(120);
  });
  it("médiane des derniers ménages, arrondie à 5 min, hors animaux", () => {
    const tasks = [
      done("2026-10-01T09:00:00Z", 90),
      done("2026-10-02T09:00:00Z", 101),
      done("2026-10-03T09:00:00Z", 97),
      done("2026-10-04T09:00:00Z", 200, { pets: 1 }),
    ];
    expect(learnedCleaningDuration("p1", tasks)).toEqual({ minutes: 95, samples: 3 });
    expect(withLearnedDuration(property, tasks).cleaningDurationMin).toBe(95);
    expect(withLearnedDuration({ ...property, learnDuration: false }, tasks).cleaningDurationMin).toBe(120);
  });
  it("heures travaillées et écart au prévu", () => {
    const tasks = [done("2026-10-05T09:00:00Z", 90), done("2026-10-06T09:00:00Z", 150), done("2026-10-06T09:00:00Z", 60, { assigneeId: "a2" })];
    const w = workedMinutes(tasks, "a1", new Date("2026-10-05T00:00:00Z"), new Date("2026-10-12T00:00:00Z"));
    expect(w).toEqual({ minutes: 240, count: 2 });
    expect(averageGap(tasks, "a1", new Date("2026-10-05T00:00:00Z"), new Date("2026-10-12T00:00:00Z"))).toBe(0);
  });
});

describe("glisser-déposer", () => {
  const task = { windowStart: "2026-10-27T10:00:00Z", windowEnd: "2026-10-27T15:00:00Z", durationMin: 120 }; // 11:00 → 16:00 à Paris
  it("pose à l'heure visée, au quart d'heure", () => {
    expect(placeTask(task, "2026-10-27", 12 * 60 + 7, "Europe/Paris")).toEqual({ ok: true, start: "2026-10-27T11:00:00.000Z", adjusted: false });
  });
  it("recale dans la fenêtre", () => {
    expect(placeTask(task, "2026-10-27", 8 * 60, "Europe/Paris")).toEqual({ ok: true, start: "2026-10-27T10:00:00.000Z", adjusted: true });
    // Trop tard : la mission doit finir avant l'arrivée
    expect(placeTask(task, "2026-10-27", 15 * 60, "Europe/Paris")).toEqual({ ok: true, start: "2026-10-27T13:00:00.000Z", adjusted: true });
  });
  it("refuse un autre jour hors fenêtre", () => {
    expect(placeTask(task, "2026-10-29", 12 * 60, "Europe/Paris")).toEqual({ ok: false, reason: "outside_window" });
  });
});

describe("livret dans le lien", () => {
  it("aller-retour sans perte, sans jeton", async () => {
    const p = {
      id: "p1",
      name: "Loft Marais",
      addressLine: "12 rue des Gravilliers",
      postalCode: "75003",
      city: "Paris",
      timezone: "Europe/Paris",
      defaultCheckIn: "16:00",
      defaultCheckOut: "11:00",
      amenities: ["wifi", "balcony"],
      customAmenities: ["Piano"],
      guide: { token: "secret", enabled: true, wifiName: "HALO", wifiPassword: "bienvenue2026" },
    } as Property;
    const data = await encodeGuide(guidePayload(p));
    expect(data).not.toContain("secret");
    const back = await decodeGuide(data);
    expect(back?.guide.wifiPassword).toBe("bienvenue2026");
    expect(back?.amenities).toEqual(["wifi", "balcony"]);
    expect(JSON.stringify(back)).not.toContain("secret");
    expect(await decodeGuide("n'importe quoi")).toBeNull();
  });
});
