import { describe, expect, it } from "vitest";
import type { Property, Task } from "@/lib/domain/types";
import { actualMinutes, averageGap, learnedCleaningDuration, withLearnedDuration, workedMinutes } from "@/lib/engine/learning";
import { placeTask } from "@/lib/engine/schedule";
import { decodeGuide, encodeGuide, guidePayload } from "@/lib/engine/guide-link";

let n = 0;
const done = (startIso: string, minutes: number, over: Partial<Task> = {}): Task => ({
  id: `t${++n}`,
  propertyId: "p1",
  type: "turnover",
  status: "validated",
  priority: "normal",
  isAutoGenerated: true,
  windowStart: startIso,
  windowEnd: startIso,
  durationMin: 120,
  assigneeId: "a1",
  startedAt: startIso,
  completedAt: new Date(new Date(startIso).getTime() + minutes * 60_000).toISOString(),
  createdAt: startIso,
  ...over,
});

const property = { id: "p1", cleaningDurationMin: 120 } as Property;

describe("durées apprises", () => {
  it("durée réelle d'une mission pointée", () => {
    expect(actualMinutes(done("2026-10-01T09:00:00Z", 95))).toBe(95);
    expect(actualMinutes({ startedAt: "2026-10-01T09:00:00Z" })).toBeNull();
    // Pointage oublié toute la nuit : ignoré
    expect(actualMinutes(done("2026-10-01T09:00:00Z", 900))).toBeNull();
  });
  it("pas assez d'historique : on garde la durée saisie", () => {
    const tasks = [done("2026-10-01T09:00:00Z", 90), done("2026-10-02T09:00:00Z", 95)];
    expect(learnedCleaningDuration("p1", tasks)).toBeNull();
    expect(withLearnedDuration(property, tasks).cleaningDurationMin).toBe(120);
  });
  it("médiane des derniers ménages, arrondie à 5 min, hors animaux", () => {
    const tasks = [
      done("2026-10-01T09:00:00Z", 90),
      done("2026-10-02T09:00:00Z", 101),
      done("2026-10-03T09:00:00Z", 97),
      done("2026-10-04T09:00:00Z", 200, { pets: 1 }),
    ];
    expect(learnedCleaningDuration("p1", tasks)).toEqual({ minutes: 95, samples: 3 });
    expect(withLearnedDuration(property, tasks).cleaningDurationMin).toBe(95);
    expect(withLearnedDuration({ ...property, learnDuration: false }, tasks).cleaningDurationMin).toBe(120);
  });
  it("heures travaillées et écart au prévu", () => {
    const tasks = [done("2026-10-05T09:00:00Z", 90), done("2026-10-06T09:00:00Z", 150), done("2026-10-06T09:00:00Z", 60, { assigneeId: "a2" })];
    const w = workedMinutes(tasks, "a1", new Date("2026-10-05T00:00:00Z"), new Date("2026-10-12T00:00:00Z"));
    expect(w).toEqual({ minutes: 240, count: 2 });
    expect(averageGap(tasks, "a1", new Date("2026-10-05T00:00:00Z"), new Date("2026-10-12T00:00:00Z"))).toBe(0);
  });
});

describe("glisser-déposer", () => {
  const task = { windowStart: "2026-10-27T10:00:00Z", windowEnd: "2026-10-27T15:00:00Z", durationMin: 120 }; // 11:00 → 16:00 à Paris
  it("pose à l'heure visée, au quart d'heure", () => {
    expect(placeTask(task, "2026-10-27", 12 * 60 + 7, "Europe/Paris")).toEqual({ ok: true, start: "2026-10-27T11:00:00.000Z", adjusted: false });
  });
  it("recale dans la fenêtre", () => {
    expect(placeTask(task, "2026-10-27", 8 * 60, "Europe/Paris")).toEqual({ ok: true, start: "2026-10-27T10:00:00.000Z", adjusted: true });
    // Trop tard : la mission doit finir avant l'arrivée
    expect(placeTask(task, "2026-10-27", 15 * 60, "Europe/Paris")).toEqual({ ok: true, start: "2026-10-27T13:00:00.000Z", adjusted: true });
  });
  it("refuse un autre jour hors fenêtre", () => {
    expect(placeTask(task, "2026-10-29", 12 * 60, "Europe/Paris")).toEqual({ ok: false, reason: "outside_window" });
  });
});

describe("livret dans le lien", () => {
  it("aller-retour sans perte, sans jeton", async () => {
    const p = {
      id: "p1",
      name: "Loft Marais",
      addressLine: "12 rue des Gravilliers",
      postalCode: "75003",
      city: "Paris",
      timezone: "Europe/Paris",
      defaultCheckIn: "16:00",
      defaultCheckOut: "11:00",
      amenities: ["wifi", "balcony"],
      customAmenities: ["Piano"],
      guide: { token: "secret", enabled: true, wifiName: "HALO", wifiPassword: "bienvenue2026", accessInfo: "Code 0000 boîte à clés" },
    } as Property;
    const data = await encodeGuide(guidePayload(p));
    expect(data).not.toContain("secret");
    const back = await decodeGuide(data);
    expect(back?.guide.wifiPassword).toBe("bienvenue2026");
    expect(back?.amenities).toEqual(["wifi", "balcony"]);
    expect(JSON.stringify(back)).not.toContain("secret");
    // Les infos d'accès ne voyagent jamais dans un lien non révocable
    expect(JSON.stringify(back)).not.toContain("0000");
    expect(await decodeGuide("n'importe quoi")).toBeNull();
  });
});

describe("reprise et répartition", () => {
  it("une mission reprise n'alimente pas l'apprentissage mais compte ses heures", () => {
    const tasks = [
      done("2026-10-01T09:00:00Z", 90),
      done("2026-10-02T09:00:00Z", 95),
      done("2026-10-03T09:00:00Z", 30, { previousWorkMin: 100 }),
    ];
    expect(learnedCleaningDuration("p1", tasks)).toBeNull(); // 2 ménages fiables seulement
    expect(workedMinutes(tasks, "a1", new Date("2026-10-01T00:00:00Z"), new Date("2026-10-04T00:00:00Z")).minutes).toBe(90 + 95 + 130);
  });
  it("la répartition automatique ne crée jamais de chevauchement détecté", async () => {
    const { autoAssign, detectConflicts } = await import("@/lib/engine/conflicts");
    const base = (id: string, start: string, end: string, dur: number, over: Partial<Task> = {}): Task => ({
      id, propertyId: "p1", type: "turnover", status: "unassigned", priority: "normal", isAutoGenerated: true,
      windowStart: start, windowEnd: end, durationMin: dur, createdAt: start, ...over,
    });
    const busy = base("busy", "2026-10-27T09:00:00Z", "2026-10-27T15:00:00Z", 150, { status: "assigned", assigneeId: "a", scheduledStart: "2026-10-27T09:00:00Z" });
    const todo = [
      base("t1", "2026-10-27T09:00:00Z", "2026-10-27T14:00:00Z", 120),
      base("t2", "2026-10-27T09:00:00Z", "2026-10-27T12:00:00Z", 120),
      base("t3", "2026-10-27T10:00:00Z", "2026-10-27T16:00:00Z", 180),
    ];
    const plan = autoAssign(todo, ["a", "b"], [busy]);
    const after = [busy, ...todo.map((x) => {
      const p = plan.find((a) => a.taskId === x.id);
      return p ? { ...x, assigneeId: p.agentId, scheduledStart: p.scheduledStart, status: "assigned" as const } : x;
    })];
    expect(detectConflicts(after)).toEqual([]);
    // Durées respectées : chaque mission placée finit dans sa fenêtre
    for (const p of plan) {
      const x = todo.find((t) => t.id === p.taskId)!;
      expect(new Date(p.scheduledStart).getTime() + x.durationMin * 60_000).toBeLessThanOrEqual(new Date(x.windowEnd).getTime());
    }
  });
});

describe("conflits : créneaux planifiés, jamais les fenêtres", () => {
  const mk = (id: string, over: Partial<Task>): Task => ({
    id, propertyId: "p1", type: "turnover", status: "assigned", priority: "normal", isAutoGenerated: true,
    windowStart: "2026-10-27T10:00:00Z", windowEnd: "2026-10-28T15:00:00Z", durationMin: 90, createdAt: "2026-10-27T00:00:00Z", ...over,
  });
  it("un départ terminé puis un ménage du même agent ne se chevauchent pas", async () => {
    const { detectConflicts } = await import("@/lib/engine/conflicts");
    const out = mk("out", { type: "check_out", status: "validated", assigneeId: "k", scheduledStart: "2026-10-27T09:45:00Z", durationMin: 20, windowStart: "2026-10-27T09:45:00Z", windowEnd: "2026-10-27T11:00:00Z" });
    const clean = mk("clean", { status: "in_progress", assigneeId: "k", scheduledStart: "2026-10-27T10:30:00Z", startedAt: "2026-10-27T10:32:00Z" });
    expect(detectConflicts([out, clean])).toEqual([]);
  });
  it("une longue fenêtre ne bloque pas l'agenda : seul le créneau compte", async () => {
    const { detectConflicts } = await import("@/lib/engine/conflicts");
    const a = mk("a", { assigneeId: "k", scheduledStart: "2026-10-27T10:00:00Z" }); // 10:00-11:30 UTC
    const b = mk("b", { propertyId: "p2", assigneeId: "k", scheduledStart: "2026-10-27T12:00:00Z" }); // autre logement, plus tard
    expect(detectConflicts([a, b])).toEqual([]);
    const c = mk("c", { propertyId: "p2", assigneeId: "k", scheduledStart: "2026-10-27T11:00:00Z" }); // chevauche a
    expect(detectConflicts([a, c]).map((x) => x.kind)).toEqual(["overlap", "overlap"]);
  });
  it("une mission terminée n'occupe plus l'agenda ; la répartition ne propose rien dans le passé", async () => {
    const { autoAssign } = await import("@/lib/engine/conflicts");
    const finished = mk("f", { status: "done", assigneeId: "k", scheduledStart: "2026-10-27T10:00:00Z" });
    const todo = mk("t", { status: "unassigned", windowStart: "2026-10-27T08:00:00Z" });
    const [plan] = autoAssign([todo], ["k"], [finished], new Date("2026-10-27T09:07:00Z"));
    expect(plan.scheduledStart).toBe("2026-10-27T09:15:00.000Z");
  });
});

describe("répartition et heures réellement pointées", () => {
  it("une mission terminée bloque seulement ses heures réelles", async () => {
    const { autoAssign } = await import("@/lib/engine/conflicts");
    const finished: Task = {
      id: "f", propertyId: "p1", type: "turnover", status: "done", priority: "normal", isAutoGenerated: true,
      windowStart: "2026-10-27T08:00:00Z", windowEnd: "2026-10-27T15:00:00Z", durationMin: 120, assigneeId: "k",
      scheduledStart: "2026-10-27T08:00:00Z", startedAt: "2026-10-27T08:00:00Z", completedAt: "2026-10-27T09:00:00Z", createdAt: "2026-10-27T00:00:00Z",
    };
    const todo: Task = { ...finished, id: "t", status: "unassigned", assigneeId: undefined, scheduledStart: undefined, startedAt: undefined, completedAt: undefined, durationMin: 60 };
    const [plan] = autoAssign([todo], ["k"], [finished], new Date("2026-10-27T07:00:00Z"));
    expect(plan.scheduledStart).toBe("2026-10-27T09:00:00.000Z"); // après le travail réel (1 h), pas après 2 h prévues
  });
});

describe("faisabilité dans la fenêtre", () => {
  const base = (over: Partial<Task>): Task => ({
    id: "x", propertyId: "p1", type: "turnover", status: "unassigned", priority: "urgent", isAutoGenerated: true,
    windowStart: "2026-10-27T10:00:00Z", windowEnd: "2026-10-27T12:30:00Z", durationMin: 180, createdAt: "2026-10-27T00:00:00Z", ...over,
  });
  it("3 h de travail dans une fenêtre de 2 h 30 : il manque 30 min, irréalisable, jamais proposée", async () => {
    const { autoAssign, infeasibility, windowShortfallMin } = await import("@/lib/engine/conflicts");
    const task = base({});
    expect(windowShortfallMin(task)).toBe(30);
    expect(infeasibility(task, new Date("2026-10-27T08:00:00Z"))).toBe("window_too_short");
    expect(autoAssign([task], ["a", "b"], [], new Date("2026-10-27T08:00:00Z"))).toEqual([]);
  });
  it("fenêtre terminée sans démarrage : en retard ; plus assez de temps : signalé", async () => {
    const { infeasibility, isOverdue } = await import("@/lib/engine/conflicts");
    const task = base({ durationMin: 60 });
    expect(infeasibility(task, new Date("2026-10-27T13:00:00Z"))).toBe("window_passed");
    expect(isOverdue(task, new Date("2026-10-27T13:00:00Z"))).toBe(true);
    expect(infeasibility(task, new Date("2026-10-27T11:45:00Z"))).toBe("too_late_today");
    expect(infeasibility(task, new Date("2026-10-27T09:00:00Z"))).toBeNull();
    expect(infeasibility({ ...task, status: "done" }, new Date("2026-10-27T13:00:00Z"))).toBeNull();
  });
  it("mission non assignée dont la fenêtre est ouverte depuis la veille : affichée aujourd'hui", async () => {
    const { taskAnchor, taskDayKey } = await import("@/lib/store/selectors");
    const carried = base({ windowStart: "2026-10-26T10:00:00Z", windowEnd: "2026-10-27T15:00:00Z", durationMin: 120 });
    const now = new Date("2026-10-27T08:00:00Z");
    expect(taskAnchor(carried, now)).toBe(now.toISOString());
    expect(taskDayKey(carried, { timezone: "Europe/Paris" } as Property, now)).toBe("2026-10-27");
    // Fenêtre terminée : la mission reste à sa date (en retard), elle ne glisse pas
    expect(taskDayKey(carried, { timezone: "Europe/Paris" } as Property, new Date("2026-10-27T16:00:00Z"))).toBe("2026-10-26");
  });
});
