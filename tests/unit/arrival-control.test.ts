import { describe, expect, it } from "vitest";
import type { Alert, Reservation, ServiceRequest, Task } from "@/lib/domain/types";
import { arrivalControl, arrivalCounts } from "@/lib/engine/arrival-control";

const now = new Date("2026-10-28T10:00:00Z");
const stay = (id: string, over: Partial<Reservation> = {}): Reservation =>
  ({ id, propertyId: `p_${id}`, source: "manual", checkInAt: "2026-10-28T15:00:00Z", checkOutAt: "2026-10-30T10:00:00Z", status: "confirmed", ...over }) as Reservation;
const clean = (stayId: string, over: Partial<Task> = {}): Task => ({
  id: `t_${stayId}`, propertyId: `p_${stayId}`, type: "turnover", status: "assigned", priority: "normal", isAutoGenerated: true, nextReservationId: stayId,
  windowStart: "2026-10-28T09:00:00Z", windowEnd: "2026-10-28T15:00:00Z", durationMin: 90, assigneeId: "a1", scheduledStart: "2026-10-28T11:00:00Z", createdAt: "", ...over,
});
const run = (stays: Reservation[], tasks: Task[], alerts: Alert[] = [], services: ServiceRequest[] = []) =>
  arrivalControl({ stays, tasks, alerts, services, now });

describe("poste de pilotage des arrivées", () => {
  it("prêt seulement avec un ménage validé et rien d'ouvert", () => {
    const [r] = run([stay("a")], [clean("a", { status: "validated" })]);
    expect(r).toMatchObject({ state: "ready", blockers: [] });
  });
  it("ménage planifié et faisable = en préparation, sans alerte", () => {
    const [r] = run([stay("a")], [clean("a")]);
    expect(r.state).toBe("preparing");
    expect(r.minutesLeft).toBe(300);
  });
  it("chaque blocage donne sa cause, son responsable et son action", () => {
    const [r] = run([stay("a")], [clean("a", { status: "unassigned", assigneeId: undefined })]);
    expect(r.state).toBe("blocked");
    expect(r.blockers[0]).toMatchObject({ kind: "cleaning_unassigned", responsible: { kind: "manager" }, action: { kind: "assign", taskId: "t_a" } });
    const [n] = run([stay("b")], []);
    expect(n.blockers[0]).toMatchObject({ kind: "no_cleaning", action: { kind: "create_cleaning" } });
    const [i] = run([stay("c")], [clean("c", { durationMin: 600 })]);
    expect(i.blockers[0]).toMatchObject({ kind: "cleaning_infeasible", detail: "window_too_short" });
  });
  it("à surveiller : validation en attente, correction, démarrage en retard, prestation, incident non urgent", () => {
    expect(run([stay("a")], [clean("a", { status: "done" })])[0]).toMatchObject({ state: "watch", blockers: [{ kind: "awaiting_validation", action: { kind: "review" } }] });
    expect(run([stay("a")], [clean("a", { status: "to_redo" })])[0]).toMatchObject({ state: "watch", blockers: [{ kind: "correction", responsible: { kind: "member", id: "a1" } }] });
    expect(run([stay("a")], [clean("a", { scheduledStart: "2026-10-28T09:30:00Z" })])[0].blockers[0].kind).toBe("cleaning_late_start");
    const svc = { id: "s1", reservationId: "a", status: "requested" } as ServiceRequest;
    expect(run([stay("a")], [clean("a", { status: "validated" })], [], [svc])[0]).toMatchObject({ state: "watch", blockers: [{ kind: "service_pending" }] });
    const minor = { id: "al", propertyId: "p_a", urgent: false, status: "open" } as Alert;
    expect(run([stay("a")], [clean("a", { status: "validated" })], [minor])[0].state).toBe("watch");
  });
  it("incident urgent : bloque même un ménage validé", () => {
    const urgent = { id: "al", propertyId: "p_a", urgent: true, status: "open" } as Alert;
    expect(run([stay("a")], [clean("a", { status: "validated" })], [urgent])[0]).toMatchObject({ state: "blocked", blockers: [{ kind: "urgent_incident", action: { kind: "open_incident", alertId: "al" } }] });
  });
  it("voyageur arrivé dans un logement pas prêt : bloqué, en tête", () => {
    const [r] = run([stay("a", { checkInAt: "2026-10-28T09:00:00Z" })], [clean("a", { status: "in_progress" })]);
    expect(r).toMatchObject({ state: "blocked", minutesLeft: -60, blockers: [{ kind: "guest_arrived_not_ready" }] });
  });
  it("plusieurs blocages sur une arrivée : une seule arrivée comptée", () => {
    const urgent = { id: "al", propertyId: "p_a", urgent: true, status: "open" } as Alert;
    const rows = run([stay("a"), stay("b")], [clean("a", { status: "unassigned", assigneeId: undefined }), clean("b", { status: "done" })], [urgent]);
    expect(rows[0].blockers.length).toBeGreaterThan(1);
    expect(arrivalCounts(rows)).toEqual({ blocked: 1, watch: 1, preparing: 0, ready: 0 });
    // Les plus graves d'abord
    expect(rows.map((r) => r.state)).toEqual(["blocked", "watch"]);
  });
  it("séjour annulé : ignoré", () => {
    expect(run([stay("a", { status: "cancelled" })], [])).toEqual([]);
  });
});

describe("étapes complémentaires (environnement connecté) : linge, maintenance, contrôle", () => {
  const step = (stayId: string, type: Task["type"], over: Partial<Task> = {}): Task => clean(stayId, { id: `${type}_${stayId}`, type, windowEnd: "2026-10-28T14:00:00Z", ...over });
  const runS = (tasks: Task[], linenRequired = true) => arrivalControl({ stays: [stay("a")], tasks, alerts: [], services: [], now, steps: { linenRequired } });

  it("blanchisserie : sans livraison de linge prévue, l'arrivée n'est jamais « prête »", () => {
    const [r] = runS([clean("a", { status: "validated" })]);
    expect(r).toMatchObject({ state: "watch", blockers: [{ kind: "step_missing", detail: "linen", action: { kind: "create_linen" } }] });
    expect(runS([clean("a", { status: "validated" })], false)[0].state).toBe("ready");
  });
  it("linge livré + ménage validé = prête ; linge prévu pas encore livré = en préparation, sans alerte", () => {
    expect(runS([clean("a", { status: "validated" }), step("a", "linen_delivery", { status: "done" })])[0].state).toBe("ready");
    const [p] = runS([clean("a", { status: "validated" }), step("a", "linen_delivery")]);
    expect(p).toMatchObject({ state: "preparing", blockers: [], pending: ["linen"] });
  });
  it("étape en retard = bloquée, avec son responsable ; sans agent = à surveiller", () => {
    const late = runS([clean("a", { status: "validated" }), step("a", "maintenance", { windowEnd: "2026-10-28T09:00:00Z" })], false)[0];
    expect(late).toMatchObject({ state: "blocked", blockers: [{ kind: "step_late", detail: "maintenance", responsible: { kind: "member", id: "a1" } }] });
    const un = runS([clean("a", { status: "validated" }), step("a", "maintenance", { status: "unassigned", assigneeId: undefined })], false)[0];
    expect(un).toMatchObject({ state: "watch", blockers: [{ kind: "step_unassigned", action: { kind: "assign" } }] });
  });
  it("contrôle qualité terminé = à valider ; validé = prête", () => {
    expect(runS([clean("a", { status: "validated" }), step("a", "inspection", { status: "done" })], false)[0]).toMatchObject({ state: "watch", blockers: [{ kind: "step_review", detail: "inspection" }] });
    expect(runS([clean("a", { status: "validated" }), step("a", "inspection", { status: "validated" })], false)[0].state).toBe("ready");
  });
  it("sans étapes demandées (démo), le comportement ne change pas", () => {
    const [r] = run([stay("a")], [clean("a", { status: "validated" }), step("a", "linen_delivery")]);
    expect(r).toMatchObject({ state: "ready", pending: [] });
  });
});
