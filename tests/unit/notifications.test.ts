import { describe, expect, it } from "vitest";
import type { Alert, ServiceRequest, Task } from "@/lib/domain/types";
import { buildInbox, unreadCount } from "@/lib/engine/notifications";

const now = new Date("2026-10-28T10:00:00Z");
const task = (over: Partial<Task>): Task => ({
  id: "t1", propertyId: "p1", type: "turnover", status: "assigned", priority: "normal", isAutoGenerated: true,
  windowStart: "2026-10-28T09:00:00Z", windowEnd: "2026-10-28T15:00:00Z", durationMin: 60, assigneeId: "a1", createdAt: "2026-10-27T00:00:00Z", ...over,
});
const service = { id: "s1", propertyId: "p1", kind: "private_chef", startAt: "2026-10-28T19:00:00Z", status: "requested", source: "guest", createdAt: "2026-10-28T08:00:00Z" } as ServiceRequest;
const urgent = { id: "al1", propertyId: "p1", urgent: true, status: "open", createdAt: "2026-10-28T07:00:00Z", category: "leak" } as Alert;

describe("notifications dans l'application", () => {
  it("chaque événement va à la bonne personne", () => {
    const tasks = [task({ id: "done", status: "done", completedAt: "2026-10-28T09:50:00Z" }), task({ id: "redo", status: "to_redo", correctionReason: "Douche" }), task({ id: "free", status: "unassigned", assigneeId: undefined })];
    const manager = buildInbox({ tasks, services: [service], alerts: [urgent], now, audience: "manager" });
    expect(manager.map((i) => i.kind)).toEqual(["alert_urgent", "task_to_validate", "task_unassigned", "service_requested"]);
    const agent = buildInbox({ tasks, services: [service], alerts: [urgent], now, audience: "agent", memberId: "a1" });
    expect(agent.map((i) => i.kind)).toEqual(["task_correction"]);
    expect(buildInbox({ tasks, services: [], alerts: [], now, audience: "agent", memberId: "a2" })).toEqual([]);
  });
  it("une demande de prestation n'est jamais classée comme incident critique", () => {
    const [item] = buildInbox({ tasks: [], services: [service], alerts: [], now, audience: "manager" });
    expect(item).toMatchObject({ kind: "service_requested", critical: false });
  });
  it("pas de doublon quand la même opération est rejouée ; l'état lu est conservé", () => {
    const a = buildInbox({ tasks: [], services: [service, service], alerts: [urgent], now, audience: "manager" });
    const keys = a.map((i) => i.key);
    expect(new Set(keys).size).toBe(2);
    const b = buildInbox({ tasks: [], services: [service], alerts: [urgent], now, audience: "manager" });
    expect(unreadCount(b, new Set(keys))).toBe(0);
  });
  it("les alertes critiques ne peuvent pas être rendues silencieuses", () => {
    const items = buildInbox({ tasks: [], services: [service], alerts: [urgent], now, audience: "manager", muted: ["alert_urgent", "service_requested"] });
    expect(items.map((i) => i.kind)).toEqual(["alert_urgent"]);
  });
});
