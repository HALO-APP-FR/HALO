import { describe, expect, it } from "vitest";
import type { Alert, Reservation, Task } from "@/lib/domain/types";
import { needsAttention, readinessFor } from "@/lib/engine/readiness";

const now = new Date("2026-10-28T10:00:00Z");
const stay = { id: "r2", propertyId: "p1", checkInAt: "2026-10-28T15:00:00Z", checkOutAt: "2026-10-30T10:00:00Z", status: "confirmed" } as Reservation;
const clean = (over: Partial<Task>): Task => ({
  id: "t1", propertyId: "p1", type: "turnover", status: "assigned", priority: "normal", isAutoGenerated: true, nextReservationId: "r2",
  windowStart: "2026-10-28T09:00:00Z", windowEnd: "2026-10-28T15:00:00Z", durationMin: 90, assigneeId: "a1", createdAt: "", ...over,
});
const urgent = { id: "al", propertyId: "p1", urgent: true, status: "open" } as Alert;

describe("logement prêt pour le prochain voyageur", () => {
  it("prêt seulement si le ménage relié est validé et sans incident urgent", () => {
    expect(readinessFor(stay, [clean({ status: "validated" })], [], now).level).toBe("ready");
    expect(readinessFor(stay, [clean({ status: "validated" })], [urgent], now)).toMatchObject({ level: "at_risk", urgentIncident: true });
  });
  it("chaque état intermédiaire est nommé, jamais présenté comme prêt", () => {
    expect(readinessFor(stay, [clean({ status: "done" })], [], now).level).toBe("awaiting_validation");
    expect(readinessFor(stay, [clean({ status: "in_progress" })], [], now).level).toBe("in_progress");
    expect(readinessFor(stay, [clean({ status: "to_redo" })], [], now).level).toBe("correction");
    expect(readinessFor(stay, [clean({ status: "unassigned", assigneeId: undefined })], [], now).level).toBe("unassigned");
    expect(readinessFor(stay, [clean({ durationMin: 600 })], [], now).level).toBe("at_risk");
    expect(readinessFor(stay, [], [], now).level).toBe("no_cleaning");
    expect(readinessFor(stay, [clean({ status: "cancelled" })], [], now).level).toBe("no_cleaning");
  });
  it("seuls les cas à débloquer sont remontés au responsable", () => {
    expect(needsAttention(readinessFor(stay, [clean({})], [], now))).toBe(false);
    expect(needsAttention(readinessFor(stay, [clean({ status: "in_progress" })], [], now))).toBe(false);
    expect(needsAttention(readinessFor(stay, [clean({ status: "done" })], [], now))).toBe(true);
    expect(needsAttention(readinessFor(stay, [clean({ status: "validated" })], [urgent], now))).toBe(true);
  });
});
