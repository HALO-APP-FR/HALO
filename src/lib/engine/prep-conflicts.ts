/**
 * Missions nécessaires avant une arrivée : sont-elles compatibles avec l'heure d'arrivée confirmée ?
 * Fonction PURE, d'après les seules données connues de HALO (plage, durée estimée, créneau, statut, affectation).
 * Niveaux :
 *  - impossible : même en commençant au plus tôt, la durée prévue ne tient pas avant l'arrivée ;
 *  - at_risk    : faisable, mais la plage ou le créneau dépasse l'arrivée, ou personne n'est attribué ;
 *  - unknown    : mission en cours, avancement inconnu ;
 *  - possible   : rien d'incompatible d'après les données connues (ce n'est pas une garantie).
 * Une durée estimée n'est jamais présentée comme une garantie. Rien n'est recalculé ici.
 */
import type { Task } from "@/lib/domain/types";

export type PrepLevel = "impossible" | "at_risk" | "unknown" | "possible";
export type PrepReason = "cannot_finish" | "slot_after_arrival" | "deadline_after_arrival" | "unassigned" | "in_progress" | "arrival_passed";
export interface PrepCheck {
  taskId: string;
  level: PrepLevel;
  reasons: PrepReason[];
  /** Plage fixée par un responsable (jamais recalculée automatiquement) */
  manual: boolean;
}

const ms = (s: string) => new Date(s).getTime();
const MIN = 60_000;

export function missionVsArrival(task: Pick<Task, "id" | "status" | "windowStart" | "windowEnd" | "durationMin" | "scheduledStart" | "assigneeId" | "isAutoGenerated">, checkInAt: string, now: Date): PrepCheck {
  const arrival = ms(checkInAt);
  const manual = !task.isAutoGenerated;
  const reasons: PrepReason[] = [];
  if (task.status === "in_progress") {
    if (now.getTime() >= arrival) return { taskId: task.id, level: "at_risk", reasons: ["in_progress", "arrival_passed"], manual };
    return { taskId: task.id, level: "unknown", reasons: ["in_progress"], manual };
  }
  const earliest = Math.max(ms(task.windowStart), now.getTime());
  if (earliest + task.durationMin * MIN > arrival) return { taskId: task.id, level: "impossible", reasons: ["cannot_finish"], manual };
  if (task.scheduledStart && ms(task.scheduledStart) + task.durationMin * MIN > arrival) reasons.push("slot_after_arrival");
  if (ms(task.windowEnd) > arrival) reasons.push("deadline_after_arrival");
  if (!task.assigneeId) reasons.push("unassigned");
  return { taskId: task.id, level: reasons.length ? "at_risk" : "possible", reasons, manual };
}

const OPEN = ["unassigned", "assigned", "in_progress", "to_redo"];
/** Missions liées à l'arrivée (préparation avant le séjour), hors accueil/départ qui ont lieu à l'heure même. */
export function arrivalPrepChecks(tasks: Task[], stay: { id: string; checkInAt: string }, now: Date): PrepCheck[] {
  return tasks
    .filter((t) => t.nextReservationId === stay.id && OPEN.includes(t.status) && t.type !== "check_in" && t.type !== "check_out")
    .map((t) => missionVsArrival(t, stay.checkInAt, now));
}
