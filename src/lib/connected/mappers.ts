/** Conversion lignes de base (snake_case) ↔ types métier du moteur (camelCase). */
import type { Property, Reservation, Task } from "@/lib/domain/types";

const iso = (v: string | null | undefined) => (v ? new Date(v).toISOString() : undefined);
const hhmm = (v: string | null | undefined, d: string) => (v ? v.slice(0, 5) : d);

export type Row = Record<string, unknown>;

export function toProperty(r: Row): Property {
  return {
    id: r.id as string,
    name: r.name as string,
    addressLine: (r.address_line as string) ?? undefined,
    area: (r.area as string) ?? undefined,
    city: (r.city as string) ?? "",
    postalCode: (r.postal_code as string) ?? undefined,
    countryCode: (r.country_code as string) ?? "FR",
    timezone: (r.timezone as string) ?? "Europe/Paris",
    capacity: (r.capacity as number) ?? 2,
    beds: [],
    defaultCheckIn: hhmm(r.default_check_in as string, "16:00"),
    defaultCheckOut: hhmm(r.default_check_out as string, "11:00"),
    cleaningDurationMin: (r.cleaning_duration_min as number) ?? 90,
    learnDuration: (r.learn_duration as boolean) ?? true,
    checkInService: (r.check_in_service as boolean) ?? false,
    checkOutService: (r.check_out_service as boolean) ?? false,
    instructions: (r.instructions as string) ?? undefined,
    access: { type: "key_box" },
    checklist: [],
    amenities: [],
    customAmenities: [],
    guide: { enabled: true, token: "" } as Property["guide"],
    linenParLevel: 3,
    feeds: [],
    archived: Boolean(r.archived_at),
    createdAt: iso(r.created_at as string) ?? new Date().toISOString(),
  };
}

export function toReservation(r: Row): Reservation {
  const adults = (r.adults as number) ?? 0;
  const children = (r.children as number) ?? 0;
  return {
    id: r.id as string,
    propertyId: r.property_id as string,
    source: (r.source as Reservation["source"]) ?? "manual",
    externalUid: (r.external_uid as string) ?? undefined,
    guestName: (r.guest_name as string) ?? undefined,
    guestsCount: adults + children || undefined,
    adults,
    children,
    babies: (r.babies as number) ?? 0,
    pets: (r.pets as number) ?? 0,
    checkInAt: iso(r.check_in_at as string)!,
    checkOutAt: iso(r.check_out_at as string)!,
    status: r.status as Reservation["status"],
    notes: (r.notes as string) ?? undefined,
    departedAt: iso(r.departed_at as string),
    vip: (r.vip as boolean) ?? false,
  };
}

export function toTask(r: Row): Task {
  return {
    id: r.id as string,
    propertyId: r.property_id as string,
    reservationId: (r.reservation_id as string) ?? undefined,
    nextReservationId: (r.next_reservation_id as string) ?? undefined,
    type: r.type as Task["type"],
    status: r.status as Task["status"],
    priority: r.priority as Task["priority"],
    isAutoGenerated: Boolean(r.is_auto_generated),
    title: (r.title as string) ?? undefined,
    windowStart: iso(r.window_start as string)!,
    windowEnd: iso(r.window_end as string)!,
    scheduledStart: iso(r.scheduled_start as string),
    durationMin: r.duration_min as number,
    durationLocked: Boolean(r.duration_locked),
    assigneeId: (r.assignee_id as string) ?? undefined,
    guestsCount: (r.guests_count as number) ?? undefined,
    babies: (r.babies as number) || undefined,
    pets: (r.pets as number) || undefined,
    vip: Boolean(r.vip) || undefined,
    notes: (r.notes as string) ?? undefined,
    startedAt: iso(r.started_at as string),
    completedAt: iso(r.completed_at as string),
    previousWorkMin: (r.previous_work_min as number) ?? 0,
    validatedAt: iso(r.validated_at as string),
    correctionReason: (r.correction_reason as string) ?? undefined,
    createdAt: iso(r.created_at as string) ?? new Date().toISOString(),
  };
}
